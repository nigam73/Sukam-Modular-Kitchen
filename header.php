    <script>
    document.addEventListener("DOMContentLoaded", function() {
        const searchInput = document.getElementById("popup-search");
        const suggestionsBox = document.getElementById("search-suggestions-box");

        if (searchInput && suggestionsBox) {

            searchInput.addEventListener("input", function() {
                const query = this.value.trim();

                if (query.length < 2) {
                    suggestionsBox.innerHTML = "";
                    suggestionsBox.style.display = "none";
                    return;
                }

                // HAMESHA 'search.php' PAR HIT KAREGA CHAHE AAP KISI BHI PAGE PAR HON!
                fetch(`search.php?action=suggest&query=${encodeURIComponent(query)}`)
                    .then(response => response.json())
                    .then(data => {
                        suggestionsBox.innerHTML = "";

                        if (data && data.length > 0) {
                            data.forEach(item => {
                                const row = document.createElement("div");
                                row.className = "fk-result-item-row";

                                const pageTitle = item.title;
                                const regex = new RegExp(`(${escapeRegExp(query)})`, "gi");
                                const highlightedTitle = pageTitle.replace(regex,
                                    `<span class="match-bold">$1</span>`);

                                row.innerHTML = `
                                <div class="fk-icon-box">
                                    <i class="fa-solid fa-file-lines"></i>
                                </div>
                                <div class="fk-details-box">
                                    <h4 class="fk-item-title">${highlightedTitle}</h4>
                                    <p class="fk-item-snippet">${item.desc}</p>
                                </div>
                            `;

                                // CLICK HANDLER: Direct page redirection jump logic
                                row.addEventListener("click", function(e) {
                                    e.stopPropagation();
                                    suggestionsBox.style.display = "none";
                                    window.location.href = item.url;
                                });

                                suggestionsBox.appendChild(row);
                            });
                            suggestionsBox.style.display = "block";
                        } else {
                            suggestionsBox.style.display = "none";
                        }
                    })
                    .catch(err => console.error("Dropdown error handler:", err));
            });

            // Dropdown boundary clicks dismiss handler
            document.addEventListener("click", function(e) {
                if (!e.target.closest('#form')) {
                    suggestionsBox.style.display = "none";
                }
            });
        }

        function escapeRegExp(string) {
            return string.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
        }
    });
    </script>
